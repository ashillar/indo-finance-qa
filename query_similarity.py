"""Compare the queries that InternVL, Qwen and Gemma generated for the same image.

For one input image, the three queries from each model are sent to an LLM judge
(gcp/gemini-3.7-flash via the LiteLLM gateway), which scores every cross-model
query pair for semantic similarity (0-100). The script prints a 3x3 matrix per
model pair plus a summary of how much each pair overlaps.

Setup:
    export LITELLM_API_KEY="sk-u1HdQXYpBI3BnPwZUTycJw"
    export LITELLM_BASE_URL="https://litellm.aip-cloudrun.mylab.local/v1"
    export JUDGE_MODEL="gcp/gemini-3.7-flash"

Usage:
    python query_similarity.py                 # first image present in all 3 models
    python query_similarity.py --list          # list available images
    python query_similarity.py --index 5       # pick image by position in --list
    python query_similarity.py --file "KSK-4626_p036.png"
    python query_similarity.py --source ojk --out result.json

    python query_similarity.py --all                # every image, then summary tables
    python query_similarity.py --all --limit 5      # quick test on 5 images
    python query_similarity.py --all --workers 8    # more parallel calls

--all writes to similarity_results/ and resumes: images already scored in
<source>_raw.jsonl are skipped, so rerunning only retries failures and rebuilds tables.
"""

import argparse
import csv
import json
import os
import re
from concurrent.futures import ThreadPoolExecutor, as_completed
from itertools import combinations
from pathlib import Path

import requests
import urllib3

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "json"
RESULTS_DIR = BASE_DIR / "similarity_results"

SOURCES = {
    "bi": {
        "internvl": "bi_single_final_internvl.jsonl",
        "qwen": "bi_single_qwen25_vl.jsonl",
        "gemma": "bi_single_batch2_gemma3_4b.jsonl",
    },
    "ojk": {
        "internvl": "ojk_single_final_internvl.jsonl",
        "qwen": "ojk_single_qwen25_vl.jsonl",
        "gemma": "ojk_single_final_gemma3_4b.jsonl",
    },
}
MODELS = ("internvl", "qwen", "gemma")
BASE_URL = os.environ.get("LITELLM_BASE_URL", "https://litellm.aip-cloudrun.mylab.local/v1")
JUDGE_MODEL = os.environ.get("JUDGE_MODEL", "gcp/gemini-3.7-flash")
# The gateway uses an internal certificate (curl -k), so TLS verification is off.
VERIFY_TLS = os.environ.get("LITELLM_VERIFY_TLS", "0") == "1"
SIMILAR_THRESHOLD = 70

if not VERIFY_TLS:
    urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

SYSTEM_PROMPT = """You compare questions generated by different vision-language models \
for the same page of an Indonesian financial report (Bank Indonesia / OJK).

Two queries are similar when they ask for the same information or the same reasoning \
about the page, even if worded differently or in different languages. Judge the intent \
and the information being asked for, not surface wording. Queries that are garbled, \
empty or not real questions should get low scores against everything.

Score scale:
- 90-100: same question (paraphrase)
- 70-89: same topic and largely the same information asked
- 40-69: related topic, but asks for different information
- 0-39: unrelated, or one of the queries is not a valid question

Score every pair you are given, exactly once.

Reply with JSON only, no markdown, in this shape:
{
  "pairs": [
    {"model_a": "internvl", "query_a": 1, "model_b": "qwen", "query_b": 1,
     "score": 85, "reason": "one short sentence"}
  ],
  "summary": "2-3 sentences: do the models ask similar questions?"
}
query_a / query_b are the 1-based query numbers shown in the input."""


def load_jsonl(path):
    """Map image filename -> list of query strings. Later lines win on duplicates."""
    records = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            qa = row.get("qa") or {}
            items = qa.get("result", []) if isinstance(qa, dict) else []
            records[row.get("file")] = [str(item.get("query", "")).strip() for item in items]
    return records


def load_source(source):
    data = {model: load_jsonl(DATA_DIR / name) for model, name in SOURCES[source].items()}
    common = sorted(set.intersection(*(set(d) for d in data.values())))
    return data, common


def build_prompt(filename, queries):
    lines = [f"Image: {filename}", ""]
    for model in MODELS:
        lines.append(f"## {model}")
        for i, q in enumerate(queries[model], 1):
            lines.append(f"{i}. {q or '(empty)'}")
        lines.append("")
    lines.append("Score every cross-model pair:")
    for a, b in combinations(MODELS, 2):
        for i in range(1, len(queries[a]) + 1):
            for j in range(1, len(queries[b]) + 1):
                lines.append(f"- {a} #{i} vs {b} #{j}")
    return "\n".join(lines)


def parse_json(text):
    """Parse the judge's reply, tolerating ```json fences around it."""
    text = text.strip()
    fenced = re.search(r"```(?:json)?\s*(.*?)```", text, re.DOTALL)
    if fenced:
        text = fenced.group(1)
    return json.loads(text)


def score_queries(api_key, filename, queries):
    resp = requests.post(
        f"{BASE_URL}/chat/completions",
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        json={
            "model": JUDGE_MODEL,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": build_prompt(filename, queries)},
            ],
            "temperature": 0,
            "response_format": {"type": "json_object"},
        },
        verify=VERIFY_TLS,
        timeout=180,
    )
    if not resp.ok:
        raise RuntimeError(f"LiteLLM error {resp.status_code}: {resp.text[:500]}")
    choice = resp.json()["choices"][0]
    if choice.get("finish_reason") == "length":
        raise RuntimeError("Judge reply was cut off (finish_reason=length).")
    result = parse_json(choice["message"]["content"])
    result.setdefault("pairs", [])
    result.setdefault("summary", "")
    return result


def pair_matrices(queries, result):
    """For each model pair, return the score matrix and its best-match stats."""
    scores = {}
    for p in result["pairs"]:
        try:
            key = (p["model_a"], int(p["query_a"]), p["model_b"], int(p["query_b"]))
        except (KeyError, TypeError, ValueError):
            continue
        scores[key] = p

    def lookup(a, i, b, j):
        return scores.get((a, i, b, j)) or scores.get((b, j, a, i))

    out = {}
    for a, b in combinations(MODELS, 2):
        matrix = []
        for i in range(1, len(queries[a]) + 1):
            row = []
            for j in range(1, len(queries[b]) + 1):
                p = lookup(a, i, b, j)
                row.append(int(p["score"]) if p else None)
            matrix.append(row)
        best = [max(s for s in row if s is not None) for row in matrix
                if any(s is not None for s in row)]
        out[(a, b)] = {
            "matrix": matrix,
            "lookup": lookup,
            "n": len(best),
            "matched": sum(s >= SIMILAR_THRESHOLD for s in best),
            "avg_best": sum(best) / len(best) if best else None,
        }
    return out


def print_report(filename, queries, result):
    print(f"\nImage: {filename}\n")
    for model in MODELS:
        print(f"[{model}]")
        for i, q in enumerate(queries[model], 1):
            print(f"  {i}. {q[:150] or '(empty)'}")
        print()

    print("=" * 72)
    for (a, b), stats in pair_matrices(queries, result).items():
        print(f"\n{a} (rows) vs {b} (cols)   score 0-100")
        n_b = len(queries[b])
        print(" " * 10 + "".join(f"{b[:5] + '#' + str(j):>9}" for j in range(1, n_b + 1)))
        for i, row in enumerate(stats["matrix"], 1):
            print(f"  {a[:5] + '#' + str(i):<8}" + "".join(f"{s if s is not None else '-':>9}" for s in row))
        avg = stats["avg_best"] or 0
        print(f"  -> {stats['matched']}/{stats['n']} {a} queries have a similar {b} query "
              f"(>= {SIMILAR_THRESHOLD}); avg best-match score {avg:.0f}")

    similar = sorted(
        (p for p in result["pairs"] if int(p.get("score", 0)) >= SIMILAR_THRESHOLD),
        key=lambda p: -int(p["score"]),
    )
    print("\nSimilar pairs:")
    if not similar:
        print("  none")
    for p in similar:
        print(f"  {int(p['score']):>3}  {p['model_a']}#{p['query_a']} ~ "
              f"{p['model_b']}#{p['query_b']}: {p.get('reason', '')}")

    print(f"\nSummary: {result['summary']}\n")


# ---------------------------------------------------------------------------
# --all mode: score every image, then build summary tables
# ---------------------------------------------------------------------------

def load_done(raw_path):
    """Images already scored successfully in a previous run."""
    done = {}
    if raw_path.exists():
        with open(raw_path, encoding="utf-8") as f:
            for line in f:
                try:
                    row = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if row.get("file") and "error" not in row:
                    done[row["file"]] = row
    return done


def run_all(args, api_key, data, common):
    RESULTS_DIR.mkdir(exist_ok=True)
    raw_path = RESULTS_DIR / f"{args.source}_raw.jsonl"
    done = load_done(raw_path)

    targets = common[: args.limit] if args.limit else common
    todo = [f for f in targets if f not in done]
    print(f"{len(targets)} images, {len(targets) - len(todo)} already scored, "
          f"{len(todo)} to score with {JUDGE_MODEL} ({args.workers} workers)")
    if todo and not api_key:
        raise SystemExit("Set LITELLM_API_KEY to your LiteLLM key first.")

    def work(filename):
        queries = {model: data[model][filename] for model in MODELS}
        try:
            result = score_queries(api_key, filename, queries)
            return {"file": filename, "judge": JUDGE_MODEL, "queries": queries, **result}
        except Exception as exc:  # keep going; failed images are retried on the next run
            return {"file": filename, "queries": queries, "error": str(exc)}

    failures = 0
    with open(raw_path, "a", encoding="utf-8") as out, ThreadPoolExecutor(args.workers) as pool:
        futures = [pool.submit(work, f) for f in todo]
        for n, fut in enumerate(as_completed(futures), 1):
            row = fut.result()
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
            out.flush()
            if "error" in row:
                failures += 1
                print(f"  [{n}/{len(todo)}] FAILED {row['file']}: {row['error'][:120]}")
            else:
                done[row["file"]] = row
                print(f"  [{n}/{len(todo)}] {row['file']}")

    write_tables(args.source, [done[f] for f in targets if f in done])
    if failures:
        print(f"\n{failures} images failed. Rerun the same command to retry them.")


def fmt(value, digits=1):
    return "" if value is None else round(value, digits)


def write_csv(path, rows):
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        if rows:
            writer = csv.DictWriter(f, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)


def write_tables(source, rows):
    pairs = list(combinations(MODELS, 2))
    totals = {pair: {"images": 0, "queries": 0, "matched": 0, "best_sum": 0.0,
                     "images_with_match": 0} for pair in pairs}
    per_image, long_rows = [], []

    for row in rows:
        stats = pair_matrices(row["queries"], row)
        record = {"file": row["file"]}
        avgs = []
        for a, b in pairs:
            s = stats[(a, b)]
            record[f"{a}_vs_{b}_matched"] = f"{s['matched']}/{s['n']}"
            record[f"{a}_vs_{b}_avg_best"] = fmt(s["avg_best"])
            if s["avg_best"] is not None:
                avgs.append(s["avg_best"])
                t = totals[(a, b)]
                t["images"] += 1
                t["queries"] += s["n"]
                t["matched"] += s["matched"]
                t["best_sum"] += s["avg_best"] * s["n"]
                t["images_with_match"] += s["matched"] > 0
            for i, score_row in enumerate(s["matrix"], 1):
                for j, score in enumerate(score_row, 1):
                    p = s["lookup"](a, i, b, j) or {}
                    long_rows.append({
                        "file": row["file"],
                        "model_a": a, "query_a_no": i, "query_a": row["queries"][a][i - 1],
                        "model_b": b, "query_b_no": j, "query_b": row["queries"][b][j - 1],
                        "score": "" if score is None else score,
                        "similar": "" if score is None else int(score >= SIMILAR_THRESHOLD),
                        "reason": p.get("reason", ""),
                    })
        record["overall_avg_best"] = fmt(sum(avgs) / len(avgs)) if avgs else ""
        record["summary"] = row.get("summary", "")
        per_image.append(record)
    per_image.sort(key=lambda r: -(r["overall_avg_best"] or 0))

    summary = []
    for a, b in pairs:
        t = totals[(a, b)]
        summary.append({
            "model_pair": f"{a} vs {b}",
            "images": t["images"],
            "avg_best_match_score": fmt(t["best_sum"] / t["queries"]) if t["queries"] else "",
            "pct_queries_with_similar_match": fmt(100 * t["matched"] / t["queries"]) if t["queries"] else "",
            "pct_images_with_any_match": fmt(100 * t["images_with_match"] / t["images"]) if t["images"] else "",
        })

    paths = [
        (RESULTS_DIR / f"{source}_summary.csv", summary),
        (RESULTS_DIR / f"{source}_per_image.csv", per_image),
        (RESULTS_DIR / f"{source}_pairs.csv", long_rows),
    ]
    for path, table in paths:
        write_csv(path, table)

    print(f"\n=== {source}_single: query similarity across {len(rows)} images "
          f"(similar = score >= {SIMILAR_THRESHOLD}) ===\n")
    headers = ["Model pair", "Images", "Avg best-match", "% queries matched", "% images w/ match"]
    widths = [22, 8, 16, 19, 19]
    print("".join(h.ljust(w) for h, w in zip(headers, widths)))
    print("-" * sum(widths))
    for r in summary:
        cells = [r["model_pair"], r["images"], r["avg_best_match_score"],
                 r["pct_queries_with_similar_match"], r["pct_images_with_any_match"]]
        print("".join(str(c).ljust(w) for c, w in zip(cells, widths)))

    if per_image:
        k = min(5, len(per_image) // 2) or 1
        print("\nMost overlapping images:")
        for r in per_image[:k]:
            print(f"  {r['overall_avg_best']:>5}  {r['file']}")
        print("Least overlapping images:")
        for r in per_image[-k:]:
            print(f"  {r['overall_avg_best']:>5}  {r['file']}")

    print("\nTables written:")
    for path, _ in paths:
        print(f"  {path.relative_to(BASE_DIR)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", choices=SOURCES, default="bi")
    parser.add_argument("--file", help="Image filename to compare")
    parser.add_argument("--index", type=int, default=0, help="Position in --list (default 0)")
    parser.add_argument("--list", action="store_true", help="List images present in all 3 models")
    parser.add_argument("--out", help="Optional path to save the result as JSON")
    parser.add_argument("--all", action="store_true", help="Score every image and build summary tables")
    parser.add_argument("--limit", type=int, help="With --all: only the first N images")
    parser.add_argument("--workers", type=int, default=4, help="With --all: parallel requests (default 4)")
    args = parser.parse_args()

    data, common = load_source(args.source)
    if args.list:
        for i, name in enumerate(common):
            print(f"{i:>4}  {name}")
        print(f"\n{len(common)} images present in all 3 models ({args.source}_single).")
        return

    if args.all:
        run_all(args, os.environ.get("LITELLM_API_KEY"), data, common)
        return

    if args.file:
        if args.file not in common:
            parser.error(f"{args.file!r} is not present in all 3 models. Use --list.")
        filename = args.file
    else:
        if not 0 <= args.index < len(common):
            parser.error(f"--index must be between 0 and {len(common) - 1}")
        filename = common[args.index]

    api_key = os.environ.get("LITELLM_API_KEY")
    if not api_key:
        parser.error("Set LITELLM_API_KEY to your LiteLLM key first.")

    queries = {model: data[model][filename] for model in MODELS}
    result = score_queries(api_key, filename, queries)
    print_report(filename, queries, result)

    if args.out:
        payload = {"source": args.source, "file": filename, "judge": JUDGE_MODEL,
                   "queries": queries, **result}
        Path(args.out).write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"Saved to {args.out}")


if __name__ == "__main__":
    main()
